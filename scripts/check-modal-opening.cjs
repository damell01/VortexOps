// Regression: cleanup must not send Escape while Filament is opening an action.
require.cache[require.resolve('canvas')] = { exports: {} };
const { JSDOM } = require('jsdom');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const dom = new JSDOM('<body style="overflow:hidden"><div class="fi-modal-window-ctn"></div></body>', {runScripts:'outside-only', pretendToBeVisual:true});
const w = dom.window;
w.requestAnimationFrame = () => 0;
let escapes = 0;
w.document.addEventListener('keydown', e => { if(e.key === 'Escape') escapes++; });
w.eval(fs.readFileSync('resources/js/modal-lifecycle.js','utf8').replace(/export\s*\{[^}]*\};?/g,''));
const sync = index => w.dispatchEvent(new w.CustomEvent('sync-action-modals', {detail:{id:'inventory-detail',newActionNestingIndex:index}}));
sync(0);
w.reconcile();
assert.equal(escapes,0,'opening an action must not receive cleanup Escape');
assert.equal(w.document.body.style.overflow,'hidden');
assert(w.document.querySelector('.fi-modal-window-ctn'));
sync(null);
w.reconcile();
assert.equal(escapes,1,'a closed orphan still releases the stale trap');
assert.equal(w.document.body.style.overflow,'');
assert.equal(w.document.querySelector('.fi-modal-window-ctn'),null);
w.document.body.style.overflow='hidden';
sync(0);
w.document.dispatchEvent(new w.Event('livewire:navigating'));
w.reconcile();
assert.equal(w.document.body.style.overflow,'','navigation must not retain stale mounted-action state');
w.close();
console.log('Modal opening and orphan cleanup checks passed');
