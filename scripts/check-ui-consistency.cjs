const Module = require('node:module');
const original = Module._load;
Module._load = function (name, ...args) { return name === 'canvas' ? {} : original.call(this, name, ...args); };
const { JSDOM } = require('jsdom');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
    const dom = new JSDOM('<body><div class="fi-input-wrp"><input id="field"></div><span class="fi-ta-filter-badge">Main Warehouse</span></body>', { runScripts: 'outside-only' });
    const w = dom.window;
    await new Promise(resolve => w.addEventListener('pageshow', resolve, { once: true }));
    let registrations = 0;
    const add = w.document.addEventListener.bind(w.document);
    w.document.addEventListener = (...args) => { registrations++; return add(...args); };
    w.eval(fs.readFileSync('resources/js/ui-improvements.js', 'utf8'));
    const initial = registrations;
    for (let i = 0; i < 100; i++) w.uiImprovements.init();
    assert.equal(registrations, initial, 'SPA updates must not attach more listeners');
    const field = w.document.querySelector('input');
    field.focus(); assert(field.parentElement.classList.contains('focused'));
    field.blur(); assert(!field.parentElement.classList.contains('focused'));
    const replacement = w.document.createElement('input');
    field.replaceWith(replacement); replacement.focus();
    assert(replacement.parentElement.classList.contains('focused'), 'morphed controls use delegated handlers');
    assert.equal(w.document.querySelector('.fi-ta-filter-badge').textContent, 'Main Warehouse');
    assert.equal(w.document.querySelector('.fi-ta-filters-clear-btn'), null, 'no visual-only clear filters button');
    w.eval(fs.readFileSync('resources/js/navigation-progress.js', 'utf8'));
    const event = () => new w.Event('livewire:navigate', { cancelable: true });
    w.document.dispatchEvent(event()); await Promise.resolve();
    assert.equal(w.document.querySelectorAll('#vx-nav-bar').length, 1);
    w.document.dispatchEvent(event()); await Promise.resolve();
    assert.equal(w.document.querySelectorAll('#vx-nav-bar').length, 1);
    w.document.dispatchEvent(new w.Event('livewire:navigated'));
    assert.equal(w.document.querySelector('#vx-nav-bar'), null);
    w.document.dispatchEvent(event());
    w.document.dispatchEvent(new w.Event('livewire:navigated')); await Promise.resolve();
    assert.equal(w.document.querySelector('#vx-nav-bar'), null, 'cached navigation cannot leave a stale bar');
    const cancelled = event(); cancelled.preventDefault();
    w.document.dispatchEvent(cancelled); await Promise.resolve();
    assert.equal(w.document.querySelector('#vx-nav-bar'), null);
    w.document.dispatchEvent(event()); await Promise.resolve();
    w.dispatchEvent(new w.Event('pageshow'));
    assert.equal(w.document.querySelector('#vx-nav-bar'), null);
    const modalCSS = fs.readFileSync('resources/css/modal-theme.css', 'utf8');
    assert(!/(?<![\w-])\.fi-modal\s*\{/.test(modalCSS), 'do not create a containing block on Filament positioning wrapper');
    for (const path of modalCSS.matchAll(/url\('([^']+)'\)/g)) assert(fs.existsSync('public' + path[1]), path[1]);
    const buttonCSS = fs.readFileSync('resources/css/button-hierarchy-responsive.css', 'utf8');
    assert(!/(?:^|\n)\[aria-busy="true"\]/.test(buttonCSS), 'busy region text remains visible');
    dom.window.close();
    console.log('UI consistency: repeated initialization, morphed controls, native filter ownership, SPA lifecycle and modal assets passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
