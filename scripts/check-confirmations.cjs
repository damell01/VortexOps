 w.document.querySelector('form').dispatchEvent(new w.Event('submit', { cancelable: true })); await tick();
 assert.equal(acted, 1); assert.equal(canceled, 2);
 button.click(); w.document.dispatchEvent(new w.Event('livewire:navigating')); await tick();
