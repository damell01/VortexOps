 input.value = 'DELETE'; input.dispatchEvent(new w.Event('input'));
 assert.equal(w.document.querySelector('[data-confirm]').disabled, false);
 w.document.querySelector('form').dispatchEvent(new w.Event('submit', { cancelable: true })); await tick(); assert.equal(acted, 2);
