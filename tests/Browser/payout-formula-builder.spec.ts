import { test, expect } from '@playwright/test';
import fs from 'node:fs';

test('build, preview, reject malformed input and cancel without changing rates', async ({ page }, info) => {
    await page.goto('/admin/login');
    await page.fill('input[type="email"]', 'dev@vortexbreaks.com');
    await page.fill('input[type="password"]', 'devpassword');
    await page.click('button[type="submit"]');
    await page.waitForURL(url => !url.pathname.endsWith('/login'));
    await page.goto('/admin/payment-structures');
    await page.getByRole('button', {name: 'Build a team formula', exact: true}).click();
    const modal = page.getByRole('dialog', {name: 'Edit team rates'});
    await modal.getByText('Custom payout formula for the team', {exact: true}).click();
    const builder = modal.locator('[data-vx-formula]');
    const formula = builder.getByRole('textbox', {name: 'Formula', exact: true});
    await expect(formula).toBeVisible();
    await formula.fill('');
    await builder.getByRole('button', {name: 'Whatnot net', exact: true}).click();
    await builder.getByRole('button', {name: 'Insert ×', exact: true}).click();
    await builder.getByRole('spinbutton', {name: 'Percentage', exact: true}).fill('8');
    await builder.getByRole('button', {name: 'Insert %', exact: true}).click();
    await expect(formula).toHaveValue(/whatnot_net\s+\*\s+\(8 \/ 100\)/);
    await builder.getByRole('button', {name: 'Preview calculation', exact: true}).click();
    await expect(builder.locator('output')).toHaveText('$68.00');
    await builder.getByRole('spinbutton', {name: 'Sample Whatnot net', exact: true}).fill('1000');
    await builder.getByRole('button', {name: 'Preview calculation', exact: true}).click();
    await expect(builder.locator('output')).toHaveText('$80.00');
    fs.mkdirSync('tests/Browser/screenshots/payout-formula', {recursive: true});
    await page.screenshot({path: `tests/Browser/screenshots/payout-formula/${info.project.name}.png`, fullPage: true});
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2)).toBe(false);
    await formula.fill('hours_worked hourly_rate');
    await builder.getByRole('button', {name: 'Preview calculation', exact: true}).click();
    await expect(builder.getByRole('alert').filter({hasText: 'Unexpected formula text'})).toBeVisible();
    await modal.getByRole('button', {name: 'Cancel', exact: true}).click();
    await expect(modal).not.toBeVisible();
    await page.getByRole('button', {name: 'Build a team formula', exact: true}).click();
    await page.getByText('Custom payout formula for the team', {exact: true}).click();
    await expect(page.locator('[data-vx-formula] textarea')).toHaveValue('');
});
